// Создание полного объекта WEAK_PINS
export const WEAK_PINS = {
  ...WEAK_PINS_BASE,

  // Объединяем все слабые PIN-коды
  ALL: (() => {
    const pins = new Set<string>();
    WEAK_PINS_BASE.SEQUENTIAL.forEach((pin) => pins.add(pin));
    WEAK_PINS_BASE.COMMON.forEach((pin) => pins.add(pin));
    return Array.from(pins);
  })(),
} as const;

